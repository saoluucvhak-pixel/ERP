    private async Task<JournalEntry> PostCoreAsync(SessionContext ctx, Voucher v, Company company, bool skipPermissionCheck = false)
    {
        if (!skipPermissionCheck) ctx.Require(Permissions.VoucherPost);
        if (v.Status == VoucherStatus.Posted || await db.JournalEntries.AnyAsync(j => j.CompanyId == v.CompanyId && j.VoucherId == v.Id))
            throw new DomainException(ErrorCodes.AlreadyPosted, $"Chứng từ {v.Number} đã ghi sổ.");
        if (v.Status != VoucherStatus.Approved)
            throw new DomainException(ErrorCodes.InvalidStateTransition, $"Chỉ ghi sổ chứng từ đã duyệt (hiện tại: {v.Status}).");

        await ThrowIfInvalidAsync(v, company);
        var period = await OpenPeriodForAsync(v.CompanyId, v.PostingDate);
        var regime = await db.AccountingRegimeVersions.AsNoTracking().FirstAsync(r => r.Id == company.RegimeVersionId);
        if (options.IsProduction && regime.VerificationStatus != VerificationStatus.Verified)
            throw new DomainException(ErrorCodes.RegimeNotVerified,
                $"Chế độ kế toán {regime.VersionCode} chưa được xác minh với văn bản pháp luật gốc; không được ghi sổ ở môi trường Production.");
        if (v.PostingDate < regime.EffectiveFrom || (regime.EffectiveTo is { } to && v.PostingDate > to))
            throw new DomainException(ErrorCodes.RegimeNotEffective, $"Ngày hạch toán {v.PostingDate.Vn()} ngoài hiệu lực của chế độ kế toán {regime.VersionCode}.");

        var now = clock.UtcNow;
        var entry = new JournalEntry
        {
            Id = Ids.New(), CompanyId = v.CompanyId, VoucherId = v.Id, PeriodId = period.Id, RegimeVersionId = regime.Id,
            PostingDate = v.PostingDate, VoucherType = v.VoucherType, VoucherNumber = v.Number, Description = v.Description,
            PostedAt = now, PostedBy = ctx.UserId,
        };
        entry.Lines = v.Lines.OrderBy(l => l.LineNo).Select(l => new JournalLine
        {
            Id = Ids.New(), JournalEntryId = entry.Id, CompanyId = v.CompanyId, LineNo = l.LineNo, AccountId = l.AccountId,
            PartnerId = l.PartnerId, Side = l.Side, Amount = l.Amount, ForeignCurrency = l.ForeignCurrency,
            ForeignAmount = l.ForeignAmount, ExchangeRate = l.ExchangeRate, PostingDate = v.PostingDate, Description = l.Description ?? v.Description,
            DueDate = l.DueDate, CashFlowCode = l.CashFlowCode,
        }).ToList();

        // Defence in depth: the journal itself must balance, independent of the validator.
        var signed = entry.Lines.Sum(l => (int)l.Side * l.Amount);
        if (signed != 0) throw new DomainException(ErrorCodes.VoucherUnbalanced, "Bút toán sổ cái không cân bằng.");

        db.JournalEntries.Add(entry);

        // Settlements requested on the voucher become allocations in the same transaction.
        foreach (var vl in v.Lines.Where(l => l.SettleJournalLineId is not null))
        {
            var newLine = entry.Lines.Single(l => l.LineNo == vl.LineNo);
            var target = await settlement.FindLineAsync(v.CompanyId, vl.SettleJournalLineId!.Value);
            var (debit, credit) = newLine.Side == Side.Debit ? (newLine, target) : (target, newLine);
            await settlement.AllocateCoreAsync(v.CompanyId, debit, credit, vl.Amount, v.PostingDate, Domain.Settlement.SettlementOrigins.Voucher, v.Id, ctx.UserId,
                newLine.ForeignCurrency is null ? null : newLine.ForeignAmount ?? 0);
        }
        var from = v.Status;
        v.MarkPosted(ctx.UserId, now);
        v.RowVersion++;
        AddHistory(v, from, "post", ctx.UserId);
        await Banking.PaymentOrderService.OnVoucherPostedAsync(db, v);
        await audit.AppendAsync(v.CompanyId, ctx, "voucher.post", "voucher", v.Id.ToString(),
            new { v.Number, journal = entry.Id, period = period.PeriodNo, amount = v.TotalDebit }, v.RowVersion);
        return entry;
    }

    private async Task<Voucher> TransitionAsync(SessionContext ctx, Guid id, long? expectedRowVersion, string permission, string action,
        Func<Voucher, Company, Task> apply, string? note = null)
    {
        ctx.Require(permission);
        return await db.InTransactionAsync(async () =>
        {
            var v = await LoadVoucherAsync(ctx, id);
            if (expectedRowVersion is { } rv) CheckRowVersion(v, rv);
            var company = await LoadCompanyAsync(ctx.CompanyId);
            var from = v.Status;
            await apply(v, company);
            v.RowVersion++;
            AddHistory(v, from, action, ctx.UserId, note);
            await audit.AppendAsync(ctx.CompanyId, ctx, $"voucher.{action}", "voucher", v.Id.ToString(), new { v.Number, from, to = v.Status, note }, v.RowVersion);
            await db.SaveChangesAsync();
            return v;
        });
    }

    private async Task ThrowIfInvalidAsync(Voucher v, Company company, bool deferNegativeBalance = false)
    {
        var errors = (await CollectErrorsAsync(v, company)).Where(e => !ErrorCodes.IsWarning(e.Code) && !(deferNegativeBalance && e.Code == ErrorCodes.NegativeBalance)).ToList();
        if (errors.Count > 0)
            throw new DomainException(errors[0].Code, string.Join("; ", errors.Select(e => e.LineNo is null ? e.Message : $"Dòng {e.LineNo}: {e.Message}")), errors);
    }

    private async Task<List<ValidationError>> CollectErrorsAsync(Voucher v, Company company)
    {
        var accountIds = v.Lines.Select(l => l.AccountId).Distinct().ToList();
        var partnerIds = v.Lines.Where(l => l.PartnerId.HasValue).Select(l => l.PartnerId!.Value).Distinct().ToList();
        // Load by id regardless of company so a foreign-company account is reported as such, not as missing.
        var accounts = await db.Accounts.AsNoTracking().Where(a => accountIds.Contains(a.Id)).ToDictionaryAsync(a => a.Id);
        var partners = await db.BusinessPartners.AsNoTracking().Where(p => partnerIds.Contains(p.Id)).ToDictionaryAsync(p => p.Id);
        var currencies = await db.Currencies.AsNoTracking().ToDictionaryAsync(c => c.Code, c => c.DecimalPlaces);
        var dp = currencies[company.FunctionalCurrency];

        // ACC-08: nguyên tệ theo đúng số chữ số lẻ của loại tiền. Chứng từ đảo chép nguyên dòng đã ghi sổ nên không kiểm lại (đảo được cả chứng từ cũ).
        var errors = VoucherValidator.Validate(v, accounts, partners, dp, v.VoucherType == VoucherTypes.Reversal ? null : currencies);
        var period = await db.AccountingPeriods.AsNoTracking()
            .FirstOrDefaultAsync(p => p.CompanyId == v.CompanyId && p.StartDate <= v.PostingDate && p.EndDate >= v.PostingDate);
        if (period is null) errors.Add(new(ErrorCodes.PeriodNotFound, $"Không có kỳ kế toán chứa ngày {v.PostingDate.Vn()}."));
        else if (period.Status == PeriodStatus.Locked) errors.Add(new(ErrorCodes.PeriodLocked, $"Kỳ {period.StartDate:MM/yyyy} đã khóa sổ."));

        await CheckSettlementsAsync(v, accounts, errors);
        await CheckNegativeBalancesAsync(v, accounts, errors);
        // Chứng từ do phân hệ chiết khấu thanh toán sinh ra: kiểm tra lại điều kiện nguồn (hạn, số tiền, hóa đơn) ở mọi bước gửi duyệt / duyệt / ghi sổ.
        if (v.SourceSystem == Hak.Application.Trade.PaymentDiscountService.Source)
            await Hak.Application.Trade.PaymentDiscountService.CheckVoucherAsync(db, v, errors);
        return errors;
    }

    /// <summary>Requested settlements must target an open posted line on the same account and partner, opposite side.</summary>
    private async Task CheckSettlementsAsync(Voucher v, IReadOnlyDictionary<Guid, Account> accounts, List<ValidationError> errors)
    {
        var requested = new Dictionary<Guid, decimal>();
        var requestedForeign = new Dictionary<Guid, decimal>();
        foreach (var l in v.Lines.Where(l => l.SettleJournalLineId is not null))
        {
            var target = await db.JournalLines.AsNoTracking().FirstOrDefaultAsync(j => j.Id == l.SettleJournalLineId && j.CompanyId == v.CompanyId);
            if (target is null) { errors.Add(new(ErrorCodes.SettlementMismatch, "Khoản công nợ cần thanh toán không tồn tại hoặc chưa ghi sổ.", l.LineNo)); continue; }
            if (target.AccountId != l.AccountId || target.PartnerId != l.PartnerId || l.PartnerId is null || target.Side == l.Side
                || !accounts.TryGetValue(l.AccountId, out var acc) || acc.OpenItemNature == OpenItemNature.None)
            {
                errors.Add(new(ErrorCodes.SettlementMismatch, "Dòng thanh toán phải cùng tài khoản công nợ, cùng đối tượng và ngược chiều với khoản được thanh toán.", l.LineNo));
                continue;
            }
            requested[target.Id] = requested.GetValueOrDefault(target.Id) + l.Amount;
            var (openForeign, open) = await settlement.OpenBothAsync(target);
            // Foreign items are checked against their carrying amount below, which also bounds the functional amount.
            if (target.ForeignCurrency is null && requested[target.Id] > open)
                errors.Add(new(ErrorCodes.SettlementExceedsOpen,
                    $"Thanh toán {requested[target.Id]} vượt số còn phải thanh toán {open}; tách phần vượt thành dòng ứng trước riêng.", l.LineNo));
            if (target.ForeignCurrency != l.ForeignCurrency)
            {
                errors.Add(new(ErrorCodes.SettlementMismatch,
                    $"Khoản được thanh toán theo {target.ForeignCurrency ?? "đồng tiền hạch toán"}, dòng thanh toán theo {l.ForeignCurrency ?? "đồng tiền hạch toán"}; dùng chức năng thu/chi ngoại tệ theo hóa đơn.", l.LineNo));
                continue;
            }
            if (target.ForeignCurrency is null) continue;
            // Foreign item: the settling line carries the item's carrying amount for the foreign part it settles; the gap to the
            // payment rate is an explicit realised FX gain/loss line, never hidden in the receivable/payable.
            var foreign = l.ForeignAmount ?? 0;
            requestedForeign[target.Id] = requestedForeign.GetValueOrDefault(target.Id) + foreign;
            if (requestedForeign[target.Id] > openForeign)
            {
                errors.Add(new(ErrorCodes.SettlementExceedsOpen, $"Thanh toán {requestedForeign[target.Id]} {target.ForeignCurrency} vượt số nguyên tệ còn lại {openForeign}.", l.LineNo));
                continue;
            }
            var book = foreign == 0
                ? (openForeign == 0 ? open : -1)
                : Domain.Fx.FxSettlementMath.BookValue(openForeign, open, foreign, await settlement.FunctionalDecimalsAsync(v.CompanyId));
            if (book != l.Amount)
                errors.Add(new(ErrorCodes.FxBookValue, book < 0
                    ? "Dòng chỉ mang mã loại tiền chỉ dùng để tất toán phần quy đổi còn lại khi nguyên tệ đã hết."
                    : $"{foreign} {target.ForeignCurrency} của khoản này có giá trị ghi sổ {book}; dòng thanh toán phải ghi đúng {book}, phần chênh với tỷ giá thanh toán ghi vào lãi/lỗ tỷ giá.", l.LineNo));
        }
    }

    /// <summary>
    /// Accounts with a negative-balance policy (e.g. cash funds): the running balance from the posting date
    /// onwards, including this voucher, must not drop below zero (Block) or produces a warning (Warn).
    /// </summary>
    private async Task CheckNegativeBalancesAsync(Voucher v, IReadOnlyDictionary<Guid, Account> accounts, List<ValidationError> errors)
    {
        foreach (var g in v.Lines.GroupBy(l => l.AccountId))
        {
            if (!accounts.TryGetValue(g.Key, out var acc) || acc.NegativeBalancePolicy == NegativeBalancePolicy.None) continue;
            var delta = g.Sum(l => (int)l.Side * l.Amount);
            if (delta >= 0) continue;

            var before = await db.JournalLines.Where(l => l.CompanyId == v.CompanyId && l.AccountId == acc.Id && l.PostingDate <= v.PostingDate)
                .GroupBy(l => l.Side).Select(x => new { x.Key, Total = x.Sum(y => y.Amount) }).ToListAsync();
            var later = await db.JournalLines.Where(l => l.CompanyId == v.CompanyId && l.AccountId == acc.Id && l.PostingDate > v.PostingDate)
                .GroupBy(l => new { l.PostingDate, l.Side }).Select(x => new { x.Key.PostingDate, x.Key.Side, Total = x.Sum(y => y.Amount) }).ToListAsync();
            var running = before.Sum(x => (int)x.Key * x.Total) + delta;
            var min = running;
            foreach (var day in later.GroupBy(x => x.PostingDate).OrderBy(x => x.Key))
            {
                running += day.Sum(x => (int)x.Side * x.Total);
                min = Math.Min(min, running);
            }
            if (min >= 0) continue;
            errors.Add(acc.NegativeBalancePolicy == NegativeBalancePolicy.Block
                ? new(ErrorCodes.NegativeBalance, $"Tài khoản {acc.Code} sẽ âm {-min} sau chứng từ này; chính sách không cho phép.")
                : new(ErrorCodes.NegativeBalanceWarning, $"Cảnh báo: tài khoản {acc.Code} sẽ âm {-min} sau chứng từ này."));
        }
    }

    private async Task<AccountingPeriod> OpenPeriodForAsync(Guid companyId, DateOnly date)
    {
        var p = await db.AccountingPeriods.AsNoTracking()
                    .FirstOrDefaultAsync(x => x.CompanyId == companyId && x.StartDate <= date && x.EndDate >= date)
                ?? throw new DomainException(ErrorCodes.PeriodNotFound, $"Không có kỳ kế toán chứa ngày {date.Vn()}.");
        if (p.Status == PeriodStatus.Locked)
            throw new DomainException(ErrorCodes.PeriodLocked, $"Kỳ {p.StartDate:MM/yyyy} đã khóa sổ.");
        return p;
    }

    private async Task<FiscalYear> FiscalYearForAsync(Guid companyId, DateOnly date)
        => await db.FiscalYears.AsNoTracking().FirstOrDefaultAsync(f => f.CompanyId == companyId && f.StartDate <= date && f.EndDate >= date)
           ?? throw new DomainException(ErrorCodes.FiscalYearNotFound, $"Không có năm tài chính chứa ngày {date.Vn()}.");

    private async Task<Company> LoadCompanyAsync(Guid companyId)
        => await db.Companies.AsNoTracking().FirstOrDefaultAsync(c => c.Id == companyId)
           ?? throw new DomainException(ErrorCodes.NotFound, "Công ty không tồn tại.");

    private async Task<Voucher> LoadVoucherAsync(SessionContext ctx, Guid id, bool track = true)
    {
        var q = db.Vouchers.Include(v => v.Lines).Where(v => v.Id == id && v.CompanyId == ctx.CompanyId);
        if (!track) q = q.AsNoTracking();
        // A voucher of another company is reported as not found, so existence does not leak across entities.
        return await q.FirstOrDefaultAsync() ?? throw new DomainException(ErrorCodes.NotFound, "Chứng từ không tồn tại.");
    }

    private static void CheckRowVersion(Voucher v, long expected)
    {
        if (v.RowVersion != expected)
            throw new DomainException(ErrorCodes.ConcurrencyConflict,
                $"Chứng từ {v.Number} đã được thay đổi (phiên bản {v.RowVersion}, bạn đang sửa phiên bản {expected}). Vui lòng tải lại.");
    }

    private static List<VoucherLine> BuildLines(Voucher v, IReadOnlyList<VoucherLineInput> lines)
        => lines.Select((l, i) => new VoucherLine
        {
            Id = Ids.New(), VoucherId = v.Id, CompanyId = v.CompanyId, LineNo = i + 1, AccountId = l.AccountId, PartnerId = l.PartnerId,
            Side = l.Side, Amount = l.Amount, ForeignCurrency = l.ForeignCurrency, ForeignAmount = l.ForeignAmount,
            ExchangeRate = l.ExchangeRate, Description = l.Description, DueDate = l.DueDate, SettleJournalLineId = l.SettleJournalLineId,
            CashFlowCode = Hak.Domain.Reports.CashFlowCodes.Normalize(l.CashFlowCode),
        }).ToList();

    private void AddHistory(Voucher v, VoucherStatus? from, string action, Guid userId, string? note = null)
        => db.VoucherHistory.Add(new VoucherHistory
        {
            Id = Ids.New(), CompanyId = v.CompanyId, VoucherId = v.Id, FromStatus = from, ToStatus = v.Status,
            Action = action, Note = note, UserId = userId, At = clock.UtcNow, VoucherRowVersion = v.RowVersion,
        });

