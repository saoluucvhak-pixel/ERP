public sealed record VoucherLineInput(
    Guid AccountId, Side Side, decimal Amount, Guid? PartnerId = null,
    string? ForeignCurrency = null, decimal? ForeignAmount = null, decimal? ExchangeRate = null, string? Description = null,
    DateOnly? DueDate = null, Guid? SettleJournalLineId = null, string? CashFlowCode = null);

/// <summary>Business-document metadata carried onto vouchers generated by the posting-rule engine.</summary>
public sealed record DocumentMeta(string BusinessEvent, Guid PostingRuleId, int PostingRuleVersion, Guid? MainAccountId, Guid? PartnerId,
    string? CounterpartyName = null, string? CounterpartyUnit = null);

public sealed record VoucherInput(
    string VoucherType, DateOnly VoucherDate, DateOnly PostingDate, string Description, IReadOnlyList<VoucherLineInput> Lines,
    Guid? BranchId = null, string? SourceSystem = null, string? SourceId = null, string? SourceVersion = null);

/// <summary>
/// Posting engine (docs/03). The only component that writes journal entries. Independent of UI:
/// every call carries a <see cref="SessionContext"/> and checks company scope, permission,
/// state, period, accounts, amounts, balance, idempotency and row version.
/// </summary>
public sealed class AccountingEngine(HakDbContext db, AuditService audit, IClock clock, HakRuntimeOptions options)
{
    private readonly SettlementService settlement = new(db, audit, clock);

    public Task<Voucher> CreateDraftAsync(SessionContext ctx, VoucherInput input, Guid? adjustsVoucherId = null)
    {
        if (!VoucherTypes.UserCreatable.Contains(input.VoucherType))
            throw new DomainException(ErrorCodes.ValidationFailed, $"Loại chứng từ '{input.VoucherType}' không được tạo trực tiếp.");
        return CreateDraftCoreAsync(ctx, input, adjustsVoucherId, null);
    }

    /// <summary>Entry point for the document/rule engine: rule-driven types require <paramref name="meta"/>.</summary>
    internal async Task<Voucher> CreateDraftCoreAsync(SessionContext ctx, VoucherInput input, Guid? adjustsVoucherId, DocumentMeta? meta)
    {
        ctx.Require(Permissions.VoucherCreate);
        if (!VoucherTypes.All.Contains(input.VoucherType) || input.VoucherType == VoucherTypes.Reversal
            || (VoucherTypes.RuleDriven.Contains(input.VoucherType) != (meta is not null)))
            throw new DomainException(ErrorCodes.ValidationFailed, $"Loại chứng từ '{input.VoucherType}' không hợp lệ cho thao tác này.");
        if (string.IsNullOrWhiteSpace(input.Description))
            throw new DomainException(ErrorCodes.ValidationFailed, "Diễn giải bắt buộc.");
        if ((input.SourceSystem is null) != (input.SourceId is null))
            throw new DomainException(ErrorCodes.ValidationFailed, "Nguồn chứng từ phải có cả source_system và source_id.");

        return await db.InTransactionAsync(async () =>
        {
            var company = await LoadCompanyAsync(ctx.CompanyId);
            var fy = await FiscalYearForAsync(ctx.CompanyId, input.PostingDate);
            if (input.SourceId is not null &&
                await db.Vouchers.AnyAsync(v => v.CompanyId == ctx.CompanyId && v.SourceSystem == input.SourceSystem && v.SourceId == input.SourceId
                                                 && v.Status != VoucherStatus.Cancelled))
                throw new DomainException(ErrorCodes.DuplicateSource, $"Nghiệp vụ nguồn {input.SourceSystem}/{input.SourceId} đã được ghi nhận.");

            var v = new Voucher
            {
                Id = Ids.New(), CompanyId = ctx.CompanyId, BranchId = input.BranchId, VoucherType = input.VoucherType,
                FiscalYearId = fy.Id, VoucherDate = input.VoucherDate, PostingDate = input.PostingDate,
                Description = input.Description.Trim(), CurrencyCode = company.FunctionalCurrency, Status = VoucherStatus.Draft,
                SourceSystem = input.SourceSystem, SourceId = input.SourceId, SourceVersion = input.SourceVersion,
                AdjustsVoucherId = adjustsVoucherId, CreatedAt = clock.UtcNow, CreatedBy = ctx.UserId, RowVersion = 1,
                BusinessEvent = meta?.BusinessEvent, PostingRuleId = meta?.PostingRuleId, PostingRuleVersion = meta?.PostingRuleVersion,
                MainAccountId = meta?.MainAccountId, PartnerId = meta?.PartnerId,
                CounterpartyName = meta?.CounterpartyName, CounterpartyUnit = meta?.CounterpartyUnit,
            };
            v.Number = await NextNumberAsync(ctx.CompanyId, fy, v.VoucherType);
            v.Lines = BuildLines(v, input.Lines);
            db.Vouchers.Add(v);
            AddHistory(v, null, "create", ctx.UserId);
            await audit.AppendAsync(ctx.CompanyId, ctx, "voucher.create", "voucher", v.Id.ToString(),
                new { v.Number, v.VoucherType, v.PostingDate, debit = v.TotalDebit, credit = v.TotalCredit, v.SourceSystem, v.SourceId }, v.RowVersion);
            await db.SaveChangesAsync();
            return v;
        });
    }

    /// <summary>Nguồn "HAK.*" là chứng từ do một phân hệ sinh ra; chỉ HAK.IMPORT (dữ liệu chuyển từ hệ thống cũ) vẫn sửa tay được.</summary>
    public static bool IsModuleGenerated(string? sourceSystem)
        => sourceSystem is not null && sourceSystem.StartsWith("HAK.", StringComparison.Ordinal) && sourceSystem != Setup.CatalogImportService.ImportSource;

    public Task<Voucher> UpdateDraftAsync(SessionContext ctx, Guid voucherId, long expectedRowVersion, VoucherInput input)
        => UpdateDraftCoreAsync(ctx, voucherId, expectedRowVersion, input, null);

    internal async Task<Voucher> UpdateDraftCoreAsync(SessionContext ctx, Guid voucherId, long expectedRowVersion, VoucherInput input, DocumentMeta? meta)
    {
        ctx.Require(Permissions.VoucherEditDraft);
        return await db.InTransactionAsync(async () =>
        {
            var v = await LoadVoucherAsync(ctx, voucherId);
            v.EnsureEditable();
            CheckRowVersion(v, expectedRowVersion);
            // Chứng từ chiết khấu thanh toán tính từ hóa đơn nguồn: không sửa tay ngày / số tiền / tài khoản (sửa là phá hạn chiết khấu) — hủy nháp rồi tạo lại qua phân hệ.
            if (v.SourceSystem == Hak.Application.Trade.PaymentDiscountService.Source)
                throw new DomainException(ErrorCodes.ValidationFailed, "Chứng từ chiết khấu thanh toán do phân hệ Chiết khấu thanh toán sinh ra từ hóa đơn; muốn đổi ngày, số tiền hoặc tài khoản tiền thì hủy chứng từ nháp và tạo lại ở màn Chiết khấu thanh toán.");
            // Chứng từ do phân hệ sinh ra chỉ được TÍNH LẠI ở phân hệ (hủy nháp rồi tạo lại), không sửa tay (chị chốt 21/10/2026):
            // sửa tay làm số của phân hệ (tạm ứng, vốn góp, lương, kết chuyển…) lệch với sổ cái.
            if (IsModuleGenerated(v.SourceSystem) || await db.PayrollSheets.AnyAsync(s => s.VoucherId == v.Id))
                throw new DomainException(ErrorCodes.ValidationFailed,
                    $"Chứng từ {v.Number} do phân hệ nghiệp vụ ({v.SourceSystem ?? "bảng lương"}) sinh ra nên không sửa tay; hủy chứng từ nháp rồi tính lại / tạo lại ở phân hệ đó.");
            if (VoucherTypes.RuleDriven.Contains(v.VoucherType) != (meta is not null))
                throw new DomainException(ErrorCodes.ValidationFailed, "Chứng từ nghiệp vụ (thu/chi) phải sửa qua màn hình chứng từ, không sửa định khoản trực tiếp.");
            if (meta is not null)
            {
                v.BusinessEvent = meta.BusinessEvent; v.PostingRuleId = meta.PostingRuleId; v.PostingRuleVersion = meta.PostingRuleVersion;
                v.MainAccountId = meta.MainAccountId; v.PartnerId = meta.PartnerId;
                v.CounterpartyName = meta.CounterpartyName; v.CounterpartyUnit = meta.CounterpartyUnit;
            }
            if (input.VoucherType != v.VoucherType)
                throw new DomainException(ErrorCodes.ValidationFailed, "Không được đổi loại chứng từ; hãy hủy và lập chứng từ mới.");
            var fy = await FiscalYearForAsync(ctx.CompanyId, input.PostingDate);
            if (fy.Id != v.FiscalYearId)
                throw new DomainException(ErrorCodes.ValidationFailed, "Không được chuyển chứng từ sang năm tài chính khác (số chứng từ theo năm).");

            // Người sửa nội dung nháp trở thành người lập: nếu không, người lập thật có thể bị người khác sửa rồi tự gửi và duyệt qua mặt kiểm soát hai người.
            var preparerChanged = v.CreatedBy != ctx.UserId;
            if (preparerChanged) v.CreatedBy = ctx.UserId;
            db.VoucherLines.RemoveRange(v.Lines);
            v.VoucherDate = input.VoucherDate;
            v.PostingDate = input.PostingDate;
            v.Description = input.Description.Trim();
            v.BranchId = input.BranchId;
            v.Lines = BuildLines(v, input.Lines);
            db.VoucherLines.AddRange(v.Lines);
            v.RowVersion++;
            AddHistory(v, VoucherStatus.Draft, "update", ctx.UserId);
            await audit.AppendAsync(ctx.CompanyId, ctx, "voucher.update", "voucher", v.Id.ToString(),
                new { v.Number, debit = v.TotalDebit, credit = v.TotalCredit, preparerChanged }, v.RowVersion);
            await db.SaveChangesAsync();
            return v;
        });
    }

    /// <summary>ValidateVoucher: runs every posting rule without writing anything.</summary>
    public async Task<IReadOnlyList<ValidationError>> ValidateAsync(SessionContext ctx, Guid voucherId)
    {
        ctx.Require(Permissions.VoucherView);
        var v = await LoadVoucherAsync(ctx, voucherId, track: false);
        var company = await LoadCompanyAsync(ctx.CompanyId);
        return await CollectErrorsAsync(v, company);
    }

    public Task<Voucher> SubmitAsync(SessionContext ctx, Guid id, long? expectedRowVersion = null)
        => TransitionAsync(ctx, id, expectedRowVersion, Permissions.VoucherSubmit, "submit", async (v, company) =>
        {
            // Imported (migrated) vouchers are submitted in bulk while their receipts are still drafts, so the running-balance check
            // would see an empty fund; it is enforced at approve and post, which run in date order.
            await ThrowIfInvalidAsync(v, company, deferNegativeBalance: v.SourceSystem == Setup.CatalogImportService.ImportSource);
            v.Submit(ctx.UserId);
        });

    public Task<Voucher> ApproveAsync(SessionContext ctx, Guid id, long? expectedRowVersion = null)
        => TransitionAsync(ctx, id, expectedRowVersion, Permissions.VoucherApprove, "approve", async (v, company) =>
        {
            await ThrowIfInvalidAsync(v, company);
            v.Approve(ctx.UserId, company.RequireDistinctApprover);
        });

    public Task<Voucher> RejectAsync(SessionContext ctx, Guid id, string reason, long? expectedRowVersion = null)
    {
        if (string.IsNullOrWhiteSpace(reason)) throw new DomainException(ErrorCodes.ReasonRequired, "Phải ghi lý do trả lại.");
        return TransitionAsync(ctx, id, expectedRowVersion, Permissions.VoucherApprove, "reject", (v, _) => { v.Reject(); return Task.CompletedTask; }, reason);
    }

    public Task<Voucher> CancelAsync(SessionContext ctx, Guid id, string reason, long? expectedRowVersion = null)
    {
        if (string.IsNullOrWhiteSpace(reason)) throw new DomainException(ErrorCodes.ReasonRequired, "Phải ghi lý do hủy.");
        return TransitionAsync(ctx, id, expectedRowVersion, Permissions.VoucherEditDraft, "cancel", (v, _) =>
        {
            // Đã gửi duyệt thì chứng từ đang nằm ở khâu duyệt: chỉ người lập (rút lại) hoặc người có quyền duyệt mới được hủy, không phải bất kỳ ai sửa được nháp.
            if (v.Status == VoucherStatus.Submitted && v.CreatedBy != ctx.UserId && !ctx.Permissions.Contains(Permissions.VoucherApprove))
                throw new DomainException(ErrorCodes.Forbidden, "Chứng từ đã gửi duyệt chỉ người lập hoặc người có quyền duyệt được hủy.");
            v.Cancel();
            return Task.CompletedTask;
        }, reason);
    }

    /// <summary>
    /// PostVoucher. One ACID transaction: re-validate, write journal, flip status, history, audit.
    /// A failure anywhere leaves the voucher Approved and the ledger untouched (INV-02).
    /// </summary>
    public async Task<JournalEntry> PostAsync(SessionContext ctx, Guid voucherId, long? expectedRowVersion = null)
    {
        ctx.Require(Permissions.VoucherPost);
        return await db.InTransactionAsync(async () =>
        {
            var v = await LoadVoucherAsync(ctx, voucherId);
            if (expectedRowVersion is { } rv) CheckRowVersion(v, rv);
            var company = await LoadCompanyAsync(ctx.CompanyId);
            var entry = await PostCoreAsync(ctx, v, company);
            await db.SaveChangesAsync();
            return entry;
        });
    }

    /// <summary>
    /// ReverseVoucher: creates and posts a REV voucher with mirrored lines dated <paramref name="reversalDate"/>
    /// and marks the original Reversed. The original journal is never touched.
    /// </summary>
    public Task<Voucher> ReverseAsync(SessionContext ctx, Guid voucherId, DateOnly reversalDate, string reason)
        => ReverseCoreAsync(ctx, voucherId, reversalDate, reason, allowModuleOwned: false);

    /// <summary>
    /// Creates and posts a system voucher in one step (inventory receipt/issue/costing). The business document
    /// that triggers it carries the approval (segregation of duties is checked there), so this skips Submit/Approve
    /// but still runs every posting check. The caller must hold voucher.post.
    /// </summary>
    internal async Task<Voucher> PostSystemVoucherAsync(SessionContext ctx, VoucherInput input)
    {
        ctx.Require(Permissions.VoucherPost);
        return await db.InTransactionAsync(async () =>
        {
            var v = await CreateDraftCoreAsync(ctx, input, null, null);
            var company = await LoadCompanyAsync(ctx.CompanyId);
            v.Status = VoucherStatus.Approved;
            v.SubmittedBy = ctx.UserId;
            v.ApprovedBy = ctx.UserId;
            await PostCoreAsync(ctx, v, company);
            await db.SaveChangesAsync();
            return v;
        });
    }

    internal async Task<Voucher> ReverseCoreAsync(SessionContext ctx, Guid voucherId, DateOnly reversalDate, string reason, bool allowModuleOwned)
    {
        ctx.Require(Permissions.VoucherReverse);
        if (string.IsNullOrWhiteSpace(reason)) throw new DomainException(ErrorCodes.ReasonRequired, "Phải ghi lý do đảo bút toán.");
        return await db.InTransactionAsync(async () =>
        {
            var original = await LoadVoucherAsync(ctx, voucherId);
            if (original.Status != VoucherStatus.Posted)
                throw new DomainException(ErrorCodes.InvalidStateTransition, $"Chỉ đảo được chứng từ đã ghi sổ (hiện tại: {original.Status}).");
            if (original.ReversesVoucherId is not null || original.VoucherType == VoucherTypes.Reversal)
                throw new DomainException(ErrorCodes.InvalidStateTransition,
                    $"Chứng từ {original.Number} là bút toán đảo; không đảo lại một bút toán đảo (sổ cái và phân hệ sẽ lệch nhau). Muốn ghi lại nghiệp vụ thì lập chứng từ mới.");
            if (!allowModuleOwned && original.SourceSystem is { } src && VoucherTypes.ModuleOwnedSources.Contains(src))
                throw new DomainException(ErrorCodes.InvalidStateTransition,
                    $"Chứng từ {original.Number} do phân hệ nghiệp vụ ({src}) sinh ra; đảo bằng chức năng của phân hệ đó (đảo phiếu kho, hủy lần tính giá, hủy khấu hao, hủy ghi giảm…) để sổ chi tiết và sổ cái luôn khớp.");
            if (reversalDate < original.PostingDate)
                throw new DomainException(ErrorCodes.ValidationFailed, "Ngày đảo không được trước ngày hạch toán của chứng từ gốc.");
            var matched = await (from m in db.ReconciliationMatches
                                 join l in db.JournalLines on m.JournalLineId equals l.Id
                                 join e in db.JournalEntries on l.JournalEntryId equals e.Id
                                 where e.VoucherId == original.Id && m.VoidedAt == null
                                 select m.Id).AnyAsync();
            if (matched)
                throw new DomainException(ErrorCodes.InvalidStateTransition, $"Chứng từ {original.Number} đã khớp với sao kê ngân hàng; hủy kết quả đối chiếu trước khi đảo.");
            var company = await LoadCompanyAsync(ctx.CompanyId);
            var fy = await FiscalYearForAsync(ctx.CompanyId, reversalDate);

            var rev = new Voucher
            {
                Id = Ids.New(), CompanyId = ctx.CompanyId, BranchId = original.BranchId, VoucherType = VoucherTypes.Reversal,
                FiscalYearId = fy.Id, VoucherDate = reversalDate, PostingDate = reversalDate,
                Description = $"Đảo chứng từ {original.Number}: {reason.Trim()}", CurrencyCode = original.CurrencyCode,
                ReversesVoucherId = original.Id, CreatedAt = clock.UtcNow, CreatedBy = ctx.UserId, RowVersion = 1,
            };
            rev.Number = await NextNumberAsync(ctx.CompanyId, fy, VoucherTypes.Reversal);
            rev.Lines = original.Lines.OrderBy(l => l.LineNo).Select(l => new VoucherLine
            {
                Id = Ids.New(), VoucherId = rev.Id, CompanyId = rev.CompanyId, LineNo = l.LineNo, AccountId = l.AccountId,
                PartnerId = l.PartnerId, Side = l.Side == Side.Debit ? Side.Credit : Side.Debit, Amount = l.Amount,
                ForeignCurrency = l.ForeignCurrency, ForeignAmount = l.ForeignAmount, ExchangeRate = l.ExchangeRate, Description = l.Description,
                DueDate = l.DueDate, CashFlowCode = l.CashFlowCode,
            }).ToList();
            db.Vouchers.Add(rev);
            AddHistory(rev, null, "create", ctx.UserId);
            await db.SaveChangesAsync(); // lines may only be inserted while the voucher is Draft (DB trigger)

            // The reversal is authorised by voucher.reverse itself; it skips the separate approval step.
            rev.Status = VoucherStatus.Approved;
            rev.ApprovedBy = ctx.UserId;
            var revEntry = await PostCoreAsync(ctx, rev, company, skipPermissionCheck: true);

            // Subledger: release every allocation of the original lines, then net each original line
            // against its mirror so neither stays open.
            var originalEntry = await db.JournalEntries.AsNoTracking().Include(e => e.Lines).SingleAsync(e => e.VoucherId == original.Id);
            var voided = await settlement.VoidForLinesAsync(ctx.CompanyId, originalEntry.Lines.Select(l => l.Id).ToList(), ctx.UserId,
                $"Đảo chứng từ {original.Number} bởi {rev.Number}");
            var openItemAccounts = await db.Accounts.AsNoTracking()
                .Where(a => a.CompanyId == ctx.CompanyId && a.OpenItemNature != OpenItemNature.None).Select(a => a.Id).ToListAsync();
            foreach (var ol in originalEntry.Lines.Where(l => l.PartnerId is not null && openItemAccounts.Contains(l.AccountId)))
            {
                var mirror = revEntry.Lines.Single(l => l.LineNo == ol.LineNo);
                var (debit, credit) = ol.Side == Side.Debit ? (ol, mirror) : (mirror, ol);
                await settlement.AllocateCoreAsync(ctx.CompanyId, debit, credit, ol.Amount, reversalDate, Domain.Settlement.SettlementOrigins.Reversal, rev.Id, ctx.UserId,
                    ol.ForeignCurrency is null ? null : ol.ForeignAmount ?? 0);
            }

            var from = original.Status;
            original.MarkReversed();
            await Banking.PaymentOrderService.OnVoucherReversedAsync(db, original);
            original.RowVersion++;
            AddHistory(original, from, "reverse", ctx.UserId, $"Đảo bởi {rev.Number}: {reason}");
            await audit.AppendAsync(ctx.CompanyId, ctx, "voucher.reverse", "voucher", original.Id.ToString(),
                new { original.Number, reversal = rev.Number, reversalDate, reason, voidedAllocations = voided }, original.RowVersion);
            await db.SaveChangesAsync();
            return rev;
        });
    }

    /// <summary>AdjustVoucher: a new Draft ADJ linked to a posted voucher; goes through normal approval.</summary>
    public async Task<Voucher> CreateAdjustmentAsync(SessionContext ctx, Guid originalId, VoucherInput input)
    {
        var original = await LoadVoucherAsync(ctx, originalId, track: false);
        if (original.Status != VoucherStatus.Posted)
            throw new DomainException(ErrorCodes.InvalidStateTransition, "Chỉ lập điều chỉnh cho chứng từ đã ghi sổ.");
        return await CreateDraftAsync(ctx, input with { VoucherType = VoucherTypes.Adjustment }, originalId);
    }

